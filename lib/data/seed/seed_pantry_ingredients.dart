/// Bundled pantry catalog (seed + tests). On-hand is empty.
List<PantryIngredient> bundledPantryIngredients() {
  final ingredients = <PantryIngredient>[];
  for (var i = 0; i < _pantryData.length; i++) {
    final (name, qty, unit, cat, flavors, cuisines, price, priceUnit, imgUrl,
        allergens, dietary) = _pantryData[i];
    final macros = _macrosPer100g[name];
    final spec = PurchaseSpec.fromSeedLabel(
      packageQty: qty,
      packageUnit: unit,
      priceUnit: priceUnit,
      price: price,
    );
    final row = PantryIngredient()
      ..supabaseId =
          'pantry_${name.toLowerCase().replaceAll(RegExp(r"[^a-z0-9]"), '_')}'
      ..name = name
      // On-hand starts empty; seed qty/unit are catalog package size.
      ..quantity = null
      ..unit = spec.sizeUnit
      ..category = cat
      ..flavorProfiles = List<String>.from(flavors)
      ..cuisineTypes = List<String>.from(cuisines)
      ..lastKnownPrice = price
      ..priceCurrency = 'USD'
      ..imageUrl = imgUrl
      ..allergenTags = List<String>.from(allergens)
      ..dietaryTags = List<String>.from(dietary)
      ..inMyPantry = false
      ..sortOrder = i
      ..isBundled = true
      ..caloriesPer100g = macros?.$1
      ..proteinPer100g = macros?.$2
      ..fatPer100g = macros?.$3
      ..carbsPer100g = macros?.$4;
    spec.applyToPantry(row);
    ingredients.add(row);
  }
  return ingredients;
}

Future<void> seedPantryIngredients() async {
  // PantryIngredient moved to Drift (S1).
  final ingredients = bundledPantryIngredients();
  if (await pantryIngredientCountInDrift() == 0) {
    await seedPantryIngredientsToDrift(ingredients);
  } else {
    // Existing installs: add only newly catalogued ingredients (keep inMyPantry).
    await insertMissingPantryIngredientsToDrift(ingredients);
    // Backfill USDA macros for rows that were inserted before macros existed.
    await patchMissingPantryMacrosInDrift(_macrosPer100g);
  }
}
